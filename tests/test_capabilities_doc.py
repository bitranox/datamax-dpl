"""docs/capabilities.md stays in step with the printer profiles.

The model tables in that document are generated by ``scripts/gen_capabilities.py``. These tests run
the generator the way a maintainer does (a separate Python process) and compare its output with the
committed document, so a change to ``domain/profiles.py`` without a regenerated document fails here.
"""

from __future__ import annotations

import os
import subprocess
import sys
from pathlib import Path

import pytest

from datamax_dpl.domain.profiles import Feature, list_profiles

_ROOT = Path(__file__).resolve().parent.parent
_SCRIPT = _ROOT / "scripts" / "gen_capabilities.py"
_DOC = _ROOT / "docs" / "capabilities.md"
_BEGIN = "<!-- BEGIN GENERATED: scripts/gen_capabilities.py -->"
_END = "<!-- END GENERATED: scripts/gen_capabilities.py -->"


def _run(*args: str) -> subprocess.CompletedProcess[str]:
    """Run the generator in its own interpreter, importing the package from this checkout."""
    env = {**os.environ, "PYTHONPATH": os.pathsep.join([str(_ROOT / "src"), os.environ.get("PYTHONPATH", "")])}
    return subprocess.run(  # noqa: S603 - fixed argv: this interpreter and a script in the repository
        [sys.executable, str(_SCRIPT), *args],
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        env=env,
        cwd=_ROOT,
        check=False,
    )


def _committed_section(document: str) -> str:
    """The text between the markers, read independently of the generator's own parser."""
    _, _, rest = document.partition(_BEGIN + "\n")
    section, found, _ = rest.partition(_END)
    assert found, f"{_DOC} lacks the generated-section markers"
    return section.strip("\n") + "\n"


@pytest.mark.os_agnostic
def test_when_profiles_are_regenerated_the_committed_tables_match() -> None:
    generated = _run()

    assert generated.returncode == 0, generated.stderr
    committed = _committed_section(_DOC.read_text(encoding="utf-8"))
    assert committed == generated.stdout, "docs/capabilities.md is stale: run scripts/gen_capabilities.py --write"


@pytest.mark.os_agnostic
def test_the_generated_tables_name_every_profile_and_every_feature() -> None:
    generated = _run().stdout

    missing_models = [p.id for p in list_profiles() if f"| `{p.id}` " not in generated]
    missing_features = [f.value for f in Feature if f"`{f.value}`" not in generated]
    assert (missing_models, missing_features) == ([], [])


@pytest.mark.os_agnostic
def test_check_passes_on_the_committed_document() -> None:
    assert _run("--check").returncode == 0


@pytest.mark.os_agnostic
def test_check_fails_and_write_repairs_a_stale_copy(tmp_path: Path) -> None:
    stale = tmp_path / "capabilities.md"
    document = _DOC.read_text(encoding="utf-8")
    stale.write_text(document.replace("| `dmx-600` ", "| `dmx-999` ", 1), encoding="utf-8")

    refused = _run("--check", "--doc", str(stale))
    repaired = _run("--write", "--doc", str(stale))

    assert (refused.returncode, "stale" in refused.stderr) == (1, True)
    assert repaired.returncode == 0
    assert stale.read_text(encoding="utf-8") == document


@pytest.mark.os_agnostic
def test_a_document_without_markers_is_refused(tmp_path: Path) -> None:
    bare = tmp_path / "capabilities.md"
    bare.write_text("# no markers here\n", encoding="utf-8")

    result = _run("--check", "--doc", str(bare))

    assert result.returncode == 2
    assert "BEGIN GENERATED" in result.stderr
    assert "Traceback" not in result.stderr
